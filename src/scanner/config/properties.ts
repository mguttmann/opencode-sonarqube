/**
 * SonarQube Properties File Generation
 * Generates and writes sonar-project.properties
 */

import type { SonarQubeConfig, ScannerOptions } from "../../types/index.ts";
import { Logger } from "../../utils/logger.ts";
import { detectProjectType, detectSourceDirectories } from "./detection.ts";
import { getDefaultExclusions, getTestPatterns } from "./patterns.ts";

const logger = new Logger("scanner-config");

/**
 * Generate sonar-project.properties content
 */
export async function generatePropertiesContent(
  options: ScannerOptions,
  config?: Partial<SonarQubeConfig>,
  directory?: string
): Promise<string> {
  const dir = directory ?? process.cwd();
  const detection = await detectProjectType(dir);

  const lines: string[] = [
    "# =============================================================================",
    "# SonarQube Configuration",
    "# Generated by opencode-sonarqube plugin",
    "# =============================================================================",
    "",
    "# Project Identification",
    `sonar.projectKey=${options.projectKey}`,
  ];

  if (options.projectName) {
    lines.push(`sonar.projectName=${options.projectName}`);
  }

  // Source Configuration
  // IMPORTANT: Use detected source directories, NOT "." with inclusions
  // SonarQube 26.x has issues with sonar.inclusions - it's better to set explicit source dirs
  const exclusions = options.exclusions ?? config?.exclusions ?? getDefaultExclusions(detection);
  const sources = options.sources ?? config?.sources ?? detectSourceDirectories(dir);
  const tests = options.tests ?? config?.tests ?? sources; // Tests are usually in same dirs

  const sourceConfig = [
    "",
    "# Source Configuration",
    `sonar.sources=${sources}`,
    `sonar.tests=${tests}`,
    `sonar.test.inclusions=${getTestPatterns(detection.languages)}`,
    `sonar.exclusions=${exclusions}`,
    // NOTE: We intentionally do NOT set sonar.inclusions
    // SonarQube 26.x has issues with inclusions causing "0 files preprocessed"
    // Let SonarQube auto-detect file types based on installed language plugins
    "",
    "# Language-Specific Configuration",
  ];
  lines.push(...sourceConfig);

  // TypeScript/JavaScript specific
  if (detection.languages.includes("typescript") || detection.languages.includes("javascript")) {
    const tsJsConfig = ["", "# TypeScript/JavaScript"];
    if (detection.languages.includes("typescript")) {
      // Find ALL tsconfig.json files in the project, not just at root
      tsJsConfig.push("sonar.typescript.tsconfigPaths=**/tsconfig.json");
    }
    tsJsConfig.push("sonar.javascript.node.maxspace=4096");
    if (detection.coverageReportPath) {
      tsJsConfig.push(`sonar.javascript.lcov.reportPaths=${detection.coverageReportPath}`);
    }
    lines.push(...tsJsConfig);
  }

  // Python specific
  if (detection.languages.includes("python")) {
    lines.push(
      "",
      "# Python",
      "sonar.python.coverage.reportPaths=coverage.xml",
      "sonar.python.xunit.reportPath=test-results.xml"
    );
  }

  // Java specific
  if (detection.languages.includes("java")) {
    lines.push(
      "",
      "# Java",
      "sonar.java.binaries=target/classes",
      "sonar.java.test.binaries=target/test-classes",
      "sonar.coverage.jacoco.xmlReportPaths=target/site/jacoco/jacoco.xml"
    );
  }

  // Go specific
  if (detection.languages.includes("go")) {
    lines.push("", "# Go", "sonar.go.coverage.reportPaths=coverage.out");
  }

  // Analysis Settings
  lines.push(
    "",
    "# Analysis Settings",
    "sonar.sourceEncoding=UTF-8",
    "sonar.scm.provider=git",
    `sonar.cpd.exclusions=${getTestPatterns(detection.languages)}`
  );

  // Additional properties
  if (options.additionalProperties) {
    lines.push("", "# Additional Properties");
    for (const [key, value] of Object.entries(options.additionalProperties)) {
      lines.push(`${key}=${value}`);
    }
  }

  return lines.join("\n");
}

/**
 * Write sonar-project.properties file
 */
export async function writePropertiesFile(
  options: ScannerOptions,
  config?: Partial<SonarQubeConfig>,
  directory?: string
): Promise<string> {
  const dir = directory ?? process.cwd();
  const content = await generatePropertiesContent(options, config, dir);
  const filePath = `${dir}/sonar-project.properties`;

  await Bun.write(filePath, content);
  logger.info(`Written sonar-project.properties to ${filePath}`);

  return filePath;
}
